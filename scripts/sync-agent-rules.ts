#!/usr/bin/env bun
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { loadRuleTable, type Rule } from "./audit-rules";

export const AGENTS_FILE = "AGENTS.md";
export const CODEOWNERS_FILE = ".github/CODEOWNERS";
export const PROTECTED_PATHS_FILE = "docs/ai/protected-paths.md";

const CODEOWNERS_BEGIN = "# BEGIN: generated by scripts/sync-agent-rules.ts";
const CODEOWNERS_END = "# END: generated by scripts/sync-agent-rules.ts";
const REGENERATE = "bun scripts/sync-agent-rules.ts";

export interface Projection {
  path: string;
  content: string;
}

export interface SyncResult {
  check: boolean;
  changed: string[];
  projections: Projection[];
}

function headingOf(line: string): string | null {
  const match = /^(#{1,6})\s+(.*)$/.exec(line);
  if (!match) return null;
  return (match[2] ?? "").trim();
}

function readReadme(root: string): string {
  const file = join(root, "README.md");
  if (!existsSync(file))
    throw new Error("README.md does not exist, so the overview cannot be read.");
  return readFileSync(file, "utf8");
}

function overviewFrom(markdown: string): string {
  const lines = markdown.split("\n");
  const start = lines.findIndex((line) => headingOf(line) === "Lagan");
  if (start === -1) throw new Error("README.md has no Lagan heading.");
  const body: string[] = [];
  for (let index = start + 1; index < lines.length; index += 1) {
    const line = lines[index] ?? "";
    if (line.trim() === "---") break;
    body.push(line);
  }
  const overview = body.join("\n").trim();
  if (!overview) throw new Error("README.md has no overview paragraph.");
  return overview;
}

function codeBlockAfterHeading(markdown: string, heading: string): string {
  const lines = markdown.split("\n");
  const start = lines.findIndex((line) => headingOf(line) === heading);
  if (start === -1) throw new Error(`README.md has no "${heading}" section.`);
  for (let index = start + 1; index < lines.length; index += 1) {
    if (!(lines[index] ?? "").trim().startsWith("```")) continue;
    const body: string[] = [];
    for (let cursor = index + 1; cursor < lines.length; cursor += 1) {
      const line = lines[cursor] ?? "";
      if (line.trim().startsWith("```")) return body.join("\n");
      body.push(line);
    }
    throw new Error(`The "${heading}" code block is not closed.`);
  }
  throw new Error(`The "${heading}" section has no code block.`);
}

export function buildAgentsMd(rules: Rule[], root: string): string {
  const readme = readReadme(root);
  const overview = overviewFrom(readme);
  const setup = codeBlockAfterHeading(readme, "Quick start");
  const gates = codeBlockAfterHeading(readme, "Gates");
  const enforced = rules.filter((rule) => rule.enforced_by.length > 0).length;
  const unenforced = rules.length - enforced;

  return [
    "<!-- GENERATED FILE. DO NOT EDIT BY HAND. -->",
    `<!-- Regenerate with: ${REGENERATE} -->`,
    "",
    "# Lagan",
    "",
    overview,
    "",
    "## Setup",
    "",
    "```bash",
    setup,
    "```",
    "",
    "## Gates",
    "",
    "```bash",
    gates,
    "```",
    "",
    "## Rules",
    "",
    `The operating rules live in \`docs/ai/rules/\`, one YAML file per rule. There are ${
      rules.length
    } rules: ${enforced} enforced, ${unenforced} unenforced.`,
    "",
    "- `docs/ai/README.md` documents the format, the layers and how to add a rule.",
    "- `docs/ai/protected-paths.md` lists the guarded paths and what enforces each one.",
    "- `bun scripts/audit-rules.ts` checks the table.",
    "",
    "Read the rule file when a rule is in question. This file routes to the table and does not",
    "restate it, because a restatement is a second copy that drifts.",
    "",
  ].join("\n");
}

export function buildCodeowners(rules: Rule[], existing: string): string {
  const owners = new Map<string, Set<string>>();
  for (const rule of rules) {
    if (!rule.owner) continue;
    for (const protectedPath of rule.protects) {
      const set = owners.get(protectedPath.path) ?? new Set<string>();
      set.add(rule.owner);
      owners.set(protectedPath.path, set);
    }
  }

  const lines = [...owners.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([path, set]) => `${path} ${[...set].sort().join(" ")}`);

  const block = [CODEOWNERS_BEGIN, ...lines, CODEOWNERS_END].join("\n");
  const head = (existing.split(CODEOWNERS_BEGIN)[0] ?? "").trimEnd();
  const tail = existing.includes(CODEOWNERS_END)
    ? (existing.split(CODEOWNERS_END).slice(1).join(CODEOWNERS_END) ?? "").trimEnd()
    : "";

  return `${[head, block, tail].filter((part) => part.length > 0).join("\n")}\n`;
}

function escapeCell(value: string): string {
  return value.replace(/\|/g, "\\|");
}

function evidenceFor(rule: Rule): string {
  const ruleFile = `\`docs/ai/rules/${rule.id}.yaml\``;
  if (rule.enforced_by.length === 0) return ruleFile;
  const mechanisms = rule.enforced_by.map((enforcement) =>
    enforcement.match === undefined
      ? `\`${enforcement.path}\``
      : `\`${enforcement.path}\` (\`${enforcement.match}\`)`,
  );
  return [ruleFile, ...mechanisms].join("; ");
}

export function buildProtectedPaths(rules: Rule[]): string {
  const rows: { path: string; rule: Rule }[] = [];
  for (const rule of rules) {
    for (const protectedPath of rule.protects) {
      rows.push({ path: protectedPath.path, rule });
    }
  }
  rows.sort((left, right) =>
    left.path === right.path
      ? left.rule.id.localeCompare(right.rule.id)
      : left.path.localeCompare(right.path),
  );

  const lines = [
    "<!-- GENERATED FILE. DO NOT EDIT BY HAND. -->",
    `<!-- Regenerate with: ${REGENERATE} -->`,
    "",
    "# Protected paths",
    "",
    "The paths the rule table guards, and the evidence that guards each one.",
    "",
    "`documented` means a rule file states the protection and nothing in the repository checks it.",
    "`repository-enforced` means a mechanism in the repository enforces it.",
    "",
    "| Path pattern | Protection | Controlling evidence | Kind |",
    "| --- | --- | --- | --- |",
  ];

  for (const row of rows) {
    const protection = row.rule.protects.find((item) => item.path === row.path)?.protection;
    const kind = row.rule.enforced_by.length > 0 ? "repository-enforced" : "documented";
    lines.push(
      `| \`${escapeCell(row.path)}\` | ${escapeCell(protection ?? row.rule.title)} | ${escapeCell(
        evidenceFor(row.rule),
      )} | ${kind} |`,
    );
  }

  lines.push("");
  return lines.join("\n");
}

export function buildProjections(rules: Rule[], root: string): Projection[] {
  const codeownersFile = join(root, CODEOWNERS_FILE);
  const existingCodeowners = existsSync(codeownersFile) ? readFileSync(codeownersFile, "utf8") : "";
  return [
    { path: AGENTS_FILE, content: buildAgentsMd(rules, root) },
    { path: CODEOWNERS_FILE, content: buildCodeowners(rules, existingCodeowners) },
    { path: PROTECTED_PATHS_FILE, content: buildProtectedPaths(rules) },
  ];
}

export function syncAgentRules(options: { root: string; check: boolean }): SyncResult {
  const { rules, findings } = loadRuleTable(options.root);
  const errors = findings.filter((item) => item.severity === "error");
  if (errors.length > 0) {
    const detail = errors.map((item) => `  ${item.rule}: ${item.message}`).join("\n");
    throw new Error(`The rule table does not parse, so nothing was written.\n${detail}`);
  }

  const projections = buildProjections(rules, options.root);
  const changed: string[] = [];

  for (const projection of projections) {
    const file = join(options.root, projection.path);
    const current = existsSync(file) ? readFileSync(file, "utf8") : "";
    if (current === projection.content) continue;
    changed.push(projection.path);
    if (options.check) continue;
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, projection.content, "utf8");
  }

  return { check: options.check, changed, projections };
}

export function diffLines(expected: string, actual: string): string[] {
  const left = expected.split("\n");
  const right = actual.split("\n");
  const table: number[][] = Array.from({ length: left.length + 1 }, () =>
    new Array<number>(right.length + 1).fill(0),
  );
  for (let i = left.length - 1; i >= 0; i -= 1) {
    for (let j = right.length - 1; j >= 0; j -= 1) {
      const row = table[i] as number[];
      const nextRow = table[i + 1] as number[];
      row[j] =
        left[i] === right[j]
          ? (nextRow[j + 1] as number) + 1
          : Math.max(nextRow[j] as number, row[j + 1] as number);
    }
  }

  const out: string[] = [];
  let i = 0;
  let j = 0;
  while (i < left.length && j < right.length) {
    if (left[i] === right[j]) {
      out.push(`  ${left[i]}`);
      i += 1;
      j += 1;
    } else if ((table[i + 1]?.[j] ?? 0) >= (table[i]?.[j + 1] ?? 0)) {
      out.push(`- ${left[i]}`);
      i += 1;
    } else {
      out.push(`+ ${right[j]}`);
      j += 1;
    }
  }
  while (i < left.length) {
    out.push(`- ${left[i]}`);
    i += 1;
  }
  while (j < right.length) {
    out.push(`+ ${right[j]}`);
    j += 1;
  }
  return out;
}

function parseArgs(argv: string[]): { check: boolean; root: string } {
  let check = false;
  let root = process.cwd();
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--check") check = true;
    else if (arg === "--root") {
      const next = argv[index + 1];
      if (next) {
        root = resolve(next);
        index += 1;
      }
    }
  }
  return { check, root };
}

function isMainModule(): boolean {
  const entry = process.argv[1];
  if (!entry) return false;
  return resolve(entry) === fileURLToPath(import.meta.url);
}

if (isMainModule()) {
  const options = parseArgs(process.argv.slice(2));
  try {
    const result = syncAgentRules({ root: options.root, check: options.check });
    if (options.check) {
      if (result.changed.length === 0) {
        console.log("The projections are up to date.");
      } else {
        for (const path of result.changed) {
          const projection = result.projections.find((item) => item.path === path);
          const file = join(options.root, path);
          const actual = existsSync(file) ? readFileSync(file, "utf8") : "";
          console.log(`--- a/${path}`);
          console.log(`+++ b/${path}`);
          console.log(diffLines(projection?.content ?? "", actual).join("\n"));
        }
        console.log(`${result.changed.length} projection(s) are out of date.`);
      }
    } else if (result.changed.length === 0) {
      console.log("The projections are up to date.");
    } else {
      for (const path of result.changed) console.log(`wrote ${path}`);
    }
    process.exit(result.check && result.changed.length > 0 ? 1 : 0);
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  }
}
