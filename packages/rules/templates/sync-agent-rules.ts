#!/usr/bin/env bun
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";
import { loadRuleTable, RULES_DIR, type Rule } from "./audit-rules";

export const AGENTS_FILE = "AGENTS.md";
export const CODEOWNERS_FILE = ".github/CODEOWNERS";
export const PROTECTED_PATHS_FILE = "docs/ai/protected-paths.md";
export const CONTEXT_FILE = "docs/ai/context.yaml";
export const RULES_README = "docs/ai/README.md";

const CODEOWNERS_BEGIN = "# BEGIN: generated by bun run rules:sync";
const CODEOWNERS_END = "# END: generated by bun run rules:sync";
const REGENERATE = "bun run rules:sync";
const AUDIT_COMMAND = "bun run rules:audit";

/**
 * The paths a human owns whatever the table says.
 *
 * The rule table and the code owners file are the two files an agent would change to
 * stop the checks, so they are listed even when no rule names them.
 */
const ALWAYS_OWNED = [`${RULES_DIR}/`, CODEOWNERS_FILE];

export interface Projection {
  path: string;
  content: string;
}

export interface SyncResult {
  check: boolean;
  changed: string[];
  projections: Projection[];
}

export interface ContextSection {
  title: string;
  body: string;
}

interface Heading {
  level: number;
  title: string;
  index: number;
}

function headings(markdown: string): Heading[] {
  const found: Heading[] = [];
  markdown.split("\n").forEach((line, index) => {
    const match = /^(#{1,6})\s+(.*)$/.exec(line);
    if (!match) return;
    found.push({ level: (match[1] ?? "").length, title: (match[2] ?? "").trim(), index });
  });
  return found;
}

function readReadme(root: string): string {
  const file = join(root, "README.md");
  if (!existsSync(file))
    throw new Error("README.md does not exist, so the overview cannot be read.");
  return readFileSync(file, "utf8");
}

/**
 * The title and the overview, read from the first top level heading.
 *
 * The title is the name the repository gives itself, and the overview is the paragraph
 * under it, so the projection names the project instead of the template that built it.
 */
function overviewFrom(markdown: string): { title: string; overview: string } {
  const lines = markdown.split("\n");
  const list = headings(markdown);
  const first = list.find((heading) => heading.level === 1) ?? list[0];
  if (!first) throw new Error("README.md has no heading, so the overview cannot be read.");
  const body: string[] = [];
  for (let index = first.index + 1; index < lines.length; index += 1) {
    const line = lines[index] ?? "";
    if (line.trim() === "---") break;
    body.push(line);
  }
  const overview = body.join("\n").trim();
  if (!overview) throw new Error("README.md has no overview paragraph.");
  return { title: first.title, overview };
}

function codeBlocks(markdown: string): string[] {
  const lines = markdown.split("\n");
  const blocks: string[] = [];
  let index = 0;
  while (index < lines.length) {
    if (!(lines[index] ?? "").trim().startsWith("```")) {
      index += 1;
      continue;
    }
    const body: string[] = [];
    index += 1;
    while (index < lines.length) {
      const line = lines[index] ?? "";
      index += 1;
      if (line.trim().startsWith("```")) break;
      body.push(line);
    }
    blocks.push(body.join("\n"));
  }
  return blocks;
}

function codeBlockAfterHeading(markdown: string, names: string[]): string | undefined {
  const lines = markdown.split("\n");
  for (const heading of headings(markdown)) {
    const wanted = names.some((name) => name.toLowerCase() === heading.title.toLowerCase());
    if (!wanted) continue;
    for (let index = heading.index + 1; index < lines.length; index += 1) {
      if (!(lines[index] ?? "").trim().startsWith("```")) continue;
      const body: string[] = [];
      for (let cursor = index + 1; cursor < lines.length; cursor += 1) {
        const line = lines[cursor] ?? "";
        if (line.trim().startsWith("```")) return body.join("\n");
        body.push(line);
      }
      throw new Error(`The "${heading.title}" code block is not closed.`);
    }
    throw new Error(`The "${heading.title}" section has no code block.`);
  }
  return undefined;
}

const SETUP_HEADINGS = ["Quick start", "Getting started", "Setup", "Install"];
const GATE_HEADINGS = ["Gates", "Commands", "Checks", "Validation", "Tests"];

function setupFrom(markdown: string): string {
  const block = codeBlockAfterHeading(markdown, SETUP_HEADINGS) ?? codeBlocks(markdown)[0];
  if (block === undefined) throw new Error("README.md has no setup code block.");
  return block;
}

function gatesFrom(markdown: string): string | undefined {
  return codeBlockAfterHeading(markdown, GATE_HEADINGS) ?? codeBlocks(markdown)[1];
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/**
 * The context file.
 *
 * It holds the facts about the repository that are not constraints: the branch to cut from,
 * the queue file to update, the merge policy. The projector renders them into AGENTS.md, so
 * the facts live in a file a human edits and not in the projector's source.
 */
export function parseContext(source: string): ContextSection[] {
  let raw: unknown;
  try {
    raw = parse(source);
  } catch (error) {
    throw new Error(
      `${CONTEXT_FILE} is not valid YAML: ${error instanceof Error ? error.message : String(error)}`,
    );
  }
  if (!isRecord(raw)) throw new Error(`${CONTEXT_FILE} must be a mapping.`);
  const sections = raw.sections;
  if (!Array.isArray(sections) || sections.length === 0) {
    throw new Error(`${CONTEXT_FILE} must hold a list of sections.`);
  }
  return sections.map((section, index) => {
    if (!isRecord(section)) {
      throw new Error(`${CONTEXT_FILE} section ${index} must be a mapping.`);
    }
    const title = typeof section.title === "string" ? section.title.trim() : "";
    const body = typeof section.body === "string" ? section.body.trim() : "";
    if (!title) throw new Error(`${CONTEXT_FILE} section ${index} needs a title.`);
    if (!body) throw new Error(`${CONTEXT_FILE} section ${index} needs a body.`);
    return { title, body };
  });
}

export function readContext(root: string): ContextSection[] {
  const file = join(root, CONTEXT_FILE);
  if (!existsSync(file)) {
    throw new Error(`${CONTEXT_FILE} does not exist, so the facts cannot be projected.`);
  }
  return parseContext(readFileSync(file, "utf8"));
}

export function buildAgentsMd(rules: Rule[], context: ContextSection[], root: string): string {
  const readme = readReadme(root);
  const { title, overview } = overviewFrom(readme);
  const setup = setupFrom(readme);
  const gates = gatesFrom(readme);
  const enforced = rules.filter((rule) => rule.enforced_by.length > 0).length;
  const unenforced = rules.length - enforced;

  const lines = [
    "<!-- GENERATED FILE. DO NOT EDIT BY HAND. -->",
    `<!-- Regenerate with: ${REGENERATE} -->`,
    "",
    `# ${title}`,
    "",
    overview,
    "",
    "## Setup",
    "",
    "```bash",
    setup,
    "```",
  ];

  if (gates !== undefined) {
    lines.push("", "## Gates", "", "```bash", gates, "```");
  }

  lines.push(
    "",
    ...context.flatMap((section) => [`## ${section.title}`, "", section.body, ""]),
    "## Rules",
    "",
    `The operating rules live in \`${RULES_DIR}/\`, one YAML file per rule. There are ${
      rules.length
    } rules: ${enforced} enforced, ${unenforced} unenforced.`,
    "",
  );

  if (existsSync(join(root, RULES_README))) {
    lines.push(`- \`${RULES_README}\` documents the format, the layers and how to add a rule.`);
  }
  lines.push(
    `- \`${PROTECTED_PATHS_FILE}\` lists the guarded paths and what enforces each one.`,
    `- \`${AUDIT_COMMAND}\` checks the table.`,
    "",
    "Read the rule file when a rule is in question. This file routes to the table and does not",
    "restate it, because a restatement is a second copy that drifts.",
    "",
  );

  return lines.join("\n");
}

export function buildCodeowners(rules: Rule[], existing: string): string {
  const owners = new Map<string, Set<string>>();
  for (const rule of rules) {
    if (!rule.owner) continue;
    for (const protectedPath of rule.protects) {
      const set = owners.get(protectedPath.path) ?? new Set<string>();
      set.add(rule.owner);
      owners.set(protectedPath.path, set);
    }
  }

  const everyone = new Set<string>();
  for (const rule of rules) {
    if (rule.owner) everyone.add(rule.owner);
  }
  for (const path of ALWAYS_OWNED) {
    if (everyone.size === 0) continue;
    owners.set(path, new Set(everyone));
  }

  const lines = [...owners.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([path, set]) => `${path} ${[...set].sort().join(" ")}`);

  const block = [CODEOWNERS_BEGIN, ...lines, CODEOWNERS_END].join("\n");
  const head = (existing.split(CODEOWNERS_BEGIN)[0] ?? "").trimEnd();
  const tail = existing.includes(CODEOWNERS_END)
    ? (existing.split(CODEOWNERS_END).slice(1).join(CODEOWNERS_END) ?? "").trimEnd()
    : "";

  return `${[head, block, tail].filter((part) => part.length > 0).join("\n")}\n`;
}

function escapeCell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\r?\n/g, "<br>");
}

/**
 * A code span that survives a markdown table.
 *
 * A pipe ends a cell even inside a code span, so it is escaped. A backtick in the content
 * would close the span, so the fence grows to be longer than the longest run of backticks.
 */
function codeSpan(value: string): string {
  const escaped = value.replace(/\|/g, "\\|");
  const runs = escaped.match(/`+/g) ?? [];
  const longest = runs.reduce((max, run) => Math.max(max, run.length), 0);
  const fence = "`".repeat(longest + 1);
  const pad = escaped.startsWith("`") || escaped.endsWith("`") ? " " : "";
  return `${fence}${pad}${escaped}${pad}${fence}`;
}

/**
 * A marker in a table cell.
 *
 * A marker can be a list, and a marker can hold a newline, so the cell holds one code span
 * per line and one group per marker. A newline inside a cell would end the table row.
 */
function renderMarker(marker: string): string {
  const lines = marker.split("\n");
  while (lines.length > 1 && lines[lines.length - 1] === "") lines.pop();
  return lines.map((line) => codeSpan(line)).join("<br>");
}

function renderMarkers(markers: string | string[]): string {
  const list = Array.isArray(markers) ? markers : [markers];
  return list.map(renderMarker).join(", ");
}

function evidenceFor(rule: Rule): string {
  const ruleFile = `\`docs/ai/rules/${rule.id}.yaml\``;
  if (rule.enforced_by.length === 0) return ruleFile;
  const mechanisms = rule.enforced_by.map((enforcement) =>
    enforcement.match === undefined
      ? `\`${enforcement.path}\``
      : `\`${enforcement.path}\` (${renderMarkers(enforcement.match)})`,
  );
  return [ruleFile, ...mechanisms].join("; ");
}

export function buildProtectedPaths(rules: Rule[]): string {
  const rows: { path: string; rule: Rule }[] = [];
  for (const rule of rules) {
    for (const protectedPath of rule.protects) {
      rows.push({ path: protectedPath.path, rule });
    }
  }
  rows.sort((left, right) =>
    left.path === right.path
      ? left.rule.id.localeCompare(right.rule.id)
      : left.path.localeCompare(right.path),
  );

  const lines = [
    "<!-- GENERATED FILE. DO NOT EDIT BY HAND. -->",
    `<!-- Regenerate with: ${REGENERATE} -->`,
    "",
    "# Protected paths",
    "",
    "The paths the rule table guards, and the evidence that guards each one.",
    "",
    "`documented` means a rule file states the protection and nothing in the repository checks it.",
    "`repository-enforced` means a mechanism in the repository enforces it.",
    "",
    "| Path pattern | Protection | Controlling evidence | Kind |",
    "| --- | --- | --- | --- |",
  ];

  for (const row of rows) {
    const protection = row.rule.protects.find((item) => item.path === row.path)?.protection;
    const kind = row.rule.enforced_by.length > 0 ? "repository-enforced" : "documented";
    lines.push(
      `| \`${escapeCell(row.path)}\` | ${escapeCell(protection ?? row.rule.title)} | ${escapeCell(
        evidenceFor(row.rule),
      )} | ${kind} |`,
    );
  }

  lines.push("");
  return lines.join("\n");
}

export function buildProjections(
  rules: Rule[],
  context: ContextSection[],
  root: string,
): Projection[] {
  const codeownersFile = join(root, CODEOWNERS_FILE);
  const existingCodeowners = existsSync(codeownersFile) ? readFileSync(codeownersFile, "utf8") : "";
  return [
    { path: AGENTS_FILE, content: buildAgentsMd(rules, context, root) },
    { path: CODEOWNERS_FILE, content: buildCodeowners(rules, existingCodeowners) },
    { path: PROTECTED_PATHS_FILE, content: buildProtectedPaths(rules) },
  ];
}

export function syncAgentRules(options: { root: string; check: boolean }): SyncResult {
  const { rules, findings } = loadRuleTable(options.root);
  const errors = findings.filter((item) => item.severity === "error");
  if (errors.length > 0) {
    const detail = errors.map((item) => `  ${item.rule}: ${item.message}`).join("\n");
    throw new Error(`The rule table does not parse, so nothing was written.\n${detail}`);
  }

  const context = readContext(options.root);
  const projections = buildProjections(rules, context, options.root);
  const changed: string[] = [];

  for (const projection of projections) {
    const file = join(options.root, projection.path);
    const current = existsSync(file) ? readFileSync(file, "utf8") : "";
    if (current === projection.content) continue;
    changed.push(projection.path);
    if (options.check) continue;
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, projection.content, "utf8");
  }

  return { check: options.check, changed, projections };
}

export function diffLines(expected: string, actual: string): string[] {
  const left = expected.split("\n");
  const right = actual.split("\n");
  const table: number[][] = Array.from({ length: left.length + 1 }, () =>
    new Array<number>(right.length + 1).fill(0),
  );
  for (let i = left.length - 1; i >= 0; i -= 1) {
    for (let j = right.length - 1; j >= 0; j -= 1) {
      const row = table[i] as number[];
      const nextRow = table[i + 1] as number[];
      row[j] =
        left[i] === right[j]
          ? (nextRow[j + 1] as number) + 1
          : Math.max(nextRow[j] as number, row[j + 1] as number);
    }
  }

  const out: string[] = [];
  let i = 0;
  let j = 0;
  while (i < left.length && j < right.length) {
    if (left[i] === right[j]) {
      out.push(`  ${left[i]}`);
      i += 1;
      j += 1;
    } else if ((table[i + 1]?.[j] ?? 0) >= (table[i]?.[j + 1] ?? 0)) {
      out.push(`- ${left[i]}`);
      i += 1;
    } else {
      out.push(`+ ${right[j]}`);
      j += 1;
    }
  }
  while (i < left.length) {
    out.push(`- ${left[i]}`);
    i += 1;
  }
  while (j < right.length) {
    out.push(`+ ${right[j]}`);
    j += 1;
  }
  return out;
}

function parseArgs(argv: string[]): { check: boolean; root: string } {
  let check = false;
  let root = process.cwd();
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--check") check = true;
    else if (arg === "--root") {
      const next = argv[index + 1];
      if (next) {
        root = resolve(next);
        index += 1;
      }
    }
  }
  return { check, root };
}

function isMainModule(): boolean {
  const entry = process.argv[1];
  if (!entry) return false;
  return resolve(entry) === fileURLToPath(import.meta.url);
}

if (isMainModule()) {
  const options = parseArgs(process.argv.slice(2));
  try {
    const result = syncAgentRules({ root: options.root, check: options.check });
    if (options.check) {
      if (result.changed.length === 0) {
        console.log("The projections are up to date.");
      } else {
        for (const path of result.changed) {
          const projection = result.projections.find((item) => item.path === path);
          const file = join(options.root, path);
          const actual = existsSync(file) ? readFileSync(file, "utf8") : "";
          console.log(`--- a/${path}`);
          console.log(`+++ b/${path}`);
          console.log(diffLines(projection?.content ?? "", actual).join("\n"));
        }
        console.log(`${result.changed.length} projection(s) are out of date.`);
      }
    } else if (result.changed.length === 0) {
      console.log("The projections are up to date.");
    } else {
      for (const path of result.changed) console.log(`wrote ${path}`);
    }
    process.exit(result.check && result.changed.length > 0 ? 1 : 0);
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  }
}
